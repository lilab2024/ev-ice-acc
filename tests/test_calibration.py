OVRV_TRUE = {"k1": 0.08, "k2": 0.40, "eta": 8.0, "tau": 1.2}
IDM_TRUE = {"v0": 40.0, "delta": 20.0, "s0": 6.0, "tau": 1.1, "alpha": 1.5, "beta": 4.0}
OVRV_SPEC = {"k1": [0.001, 1.0], "k2": [0.0, 2.0], "eta": [0.0, 25.0], "tau": [0.3, 3.5]}
IDM_SPEC = {"v0": 40.0, "delta": 20.0, "s0": [0.5, 20.0], "tau": [0.3, 3.5],
            "alpha": [0.2, 4.0], "beta": [0.3, 100.0]}


def synthetic_run(model, p, run_id="synthetic"):
    """'Measured' run generated by the model itself, so the true parameters are known.

    The leader alternates between two speed levels (15 and 30 m/s) with oscillations,
    so that the constant and speed-proportional parts of the spacing are identifiable.
    """
    t = np.arange(0, 240, 0.1)
    level = np.where((t // 60) % 2 == 0, 30.0, 15.0)
    v_l = level + 1.5 * np.sin(2 * np.pi * t / 15)
    v_l = np.convolve(v_l, np.ones(30) / 30, mode="same")      # smooth the level steps
    v_l[:15], v_l[-15:] = v_l[15], v_l[-16]
    v_init = v_l[0]
    s_init = model.equilibrium_spacing(v_init, p)
    out = simulate_follower(model, p, t, v_l, s_init, v_init)
    return dict(run_id=run_id, t=t, v_l=v_l, v_f=out["v"], s=out["s"])


def test_split_and_merge_parameters():
    free, bounds, fixed = split_spec(IDM_SPEC)
    assert free == ["s0", "tau", "alpha", "beta"]
    assert fixed == {"v0": 40.0, "delta": 20.0}
    p = to_params([6.0, 1.1, 1.5, 4.0], free, fixed)
    assert p == IDM_TRUE


@pytest.mark.parametrize("model, p_true, spec", [(ovrv, OVRV_TRUE, OVRV_SPEC),
                                                 (idm, IDM_TRUE, IDM_SPEC)])
def test_batch_objective_matches_single(model, p_true, spec):
    runs = [synthetic_run(model, p_true)]
    free, bounds, fixed = split_spec(spec)
    rng = np.random.default_rng(0)
    lo = np.array([b[0] for b in bounds]); hi = np.array([b[1] for b in bounds])
    X = (lo + rng.random((10, len(free))) * (hi - lo)).T
    batch = objective_batch(X, model, free, fixed, runs)
    single = [objective(X[:, j], model, free, fixed, runs) for j in range(10)]
    assert np.allclose(batch, single, atol=1e-10)


@pytest.mark.parametrize("model, p_true, spec", [(ovrv, OVRV_TRUE, OVRV_SPEC),
                                                 (idm, IDM_TRUE, IDM_SPEC)])
def test_calibration_recovers_true_parameters(model, p_true, spec):
    """On data generated by the model itself, calibration must find the true parameters."""
    runs = [synthetic_run(model, p_true)]
    r = calibrate(model, spec, runs, seed=0, popsize=15, maxiter=300, tol=1e-6)
    assert r["objective"] < 0.05                      # spacing RMSE close to zero
    for name in r["free"]:
        assert r["params"][name] == pytest.approx(p_true[name], rel=0.05), name


def test_bound_flags():
    assert bound_flags(["beta"], [(0.3, 100.0)], [0.85]) == []
    assert bound_flags(["beta"], [(0.3, 100.0)], [0.31]) == ["beta=low"]
    assert bound_flags(["beta"], [(0.3, 100.0)], [98.0]) == ["beta=high"]
    assert bound_flags(["k2"], [(0.0, 2.0)], [0.01]) == ["k2=low"]
    assert bound_flags(["eta"], [(0.0, 25.0)], [24.626]) == []
